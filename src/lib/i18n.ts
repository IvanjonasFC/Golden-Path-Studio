function tText(s: string, lang: 'es' | 'en'): string | null {
  const key = s.trim();
  if (!key) return null;
  const map = lang === 'en' ? DICT : REV;
  if (Object.prototype.hasOwnProperty.call(map, key)) {
    return s.replace(key, map[key]);
  }
  for (let i = 0; i < PAT.length; i++) {
    const p = PAT[i];
    const rx = lang === 'en' ? p.r : p.rr;
    if (rx.test(key)) {
      const nk = key.replace(rx, lang === 'en' ? p.e : p.s);
      return s.replace(key, nk);
    }
  }
  return null;
}

function skip(node: Node): boolean {
  let p = node.parentNode as (HTMLElement | null);
  while (p && p.nodeType === 1) {
    const t = p.tagName;
    if (
      t === 'CODE' ||
      t === 'PRE' ||
      t === 'SCRIPT' ||
      t === 'STYLE' ||
      t === 'TEXTAREA' ||
      t === 'NOSCRIPT' ||
      p.hasAttribute('data-no-i18n')
    ) {
      return true;
    }
    p = p.parentNode as (HTMLElement | null);
  }
  return false;
}

function maybeText(node: Node, lang: 'es' | 'en') {
  if (!node || skip(node)) return;
  const s = node.nodeValue;
  if (!s || !/[A-Za-zÀ-ÿ]/.test(s)) return;
  const r = tText(s, lang);
  if (r != null && r !== s) {
    node.nodeValue = r;
  }
}

function transAttr(el: Element, lang: 'es' | 'en') {
  if (!el || !el.getAttribute) return;
  const map = lang === 'en' ? DICT : REV;
  const attrs = ['placeholder', 'title', 'aria-label'];
  for (let i = 0; i < attrs.length; i++) {
    const v = el.getAttribute(attrs[i]);
    if (v) {
      const key = v.trim();
      if (Object.prototype.hasOwnProperty.call(map, key) && map[key] !== v) {
        el.setAttribute(attrs[i], v.replace(key, map[key]));
      }
    }
  }
}

export function walk(root: Node | null, lang: 'es' | 'en') {
  if (!root || typeof document === 'undefined') return;
  if (root.nodeType === 3) {
    maybeText(root, lang);
    return;
  }
  if (root.nodeType !== 1) return;

  transAttr(root as Element, lang);

  // Traducir elementos con data-i18n (más robusto para nodos React estáticos)
  try {
    const dataEls = (root as Element).querySelectorAll('[data-i18n]');
    for (let i = 0; i < dataEls.length; i++) {
      const el = dataEls[i] as HTMLElement;
      const key = el.getAttribute('data-i18n') || '';
      if (!key) continue;
      if (lang === 'en') {
        el.textContent = DICT[key] || key;
      } else {
        el.textContent = key; // ES: restaurar clave original
      }
    }
  } catch (e) {}

  try {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
    const batch: Node[] = [];
    let n: Node | null = null;
    while ((n = walker.nextNode())) {
      batch.push(n);
    }
    for (let i = 0; i < batch.length; i++) {
      maybeText(batch[i], lang);
    }
    const els = (root as Element).querySelectorAll('[placeholder],[title],[aria-label]');
    for (let j = 0; j < els.length; j++) {
      transAttr(els[j], lang);
    }
  } catch (e) {}
}

let activeLang: 'es' | 'en' = 'es';
let observer: MutationObserver | null = null;

// Referencia al handler del botón para sincronizar su texto
function syncLangButton(lang: 'es' | 'en') {
  if (typeof document === 'undefined') return;
  // TopNavActions usa estado React, pero por si acaso hay algún botón con id lang-toggle
  const btn = document.getElementById('lang-toggle');
  if (btn) btn.textContent = lang === 'en' ? 'ES' : 'EN';
}

export function applyLang(lang: 'es' | 'en') {
  activeLang = lang;
  if (typeof document === 'undefined') return;

  try {
    document.documentElement.lang = lang;
  } catch (e) {}

  walk(document.body, lang);
  syncLangButton(lang);

  try {
    localStorage.setItem('lang', lang);
  } catch (e) {}

  // Notificar a componentes React suscritos (BrandEditor, etc.)
  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('app:lang-change', { detail: lang }));
  }

  // Crear el MutationObserver solo una vez y adjuntarlo a window para sobrevivir al HMR
  const w = typeof window !== 'undefined' ? (window as any) : null;
  if (w && !w.__i18nObserver && typeof MutationObserver !== 'undefined') {
    w.__i18nObserver = new MutationObserver((muts) => {
      for (let i = 0; i < muts.length; i++) {
        const m = muts[i];
        if (m.type === 'childList') {
          for (let j = 0; j < m.addedNodes.length; j++) {
            const an = m.addedNodes[j];
            if (an.nodeType === 1) walk(an, activeLang);
            else if (an.nodeType === 3) maybeText(an, activeLang);
          }
        } else if (m.type === 'characterData' && m.target) {
          maybeText(m.target, activeLang);
        } else if (m.type === 'attributes' && m.target && m.target.nodeType === 1) {
          transAttr(m.target as Element, activeLang);
        }
      }
    });

    try {
      w.__i18nObserver.observe(document.body, {
        childList: true,
        subtree: true,
        characterData: true,
        attributes: true,
        attributeFilter: ['placeholder', 'title', 'aria-label']
      });
    } catch (e) {}
  }
  // Actualizar referencia local del observer
  if (w && w.__i18nObserver) observer = w.__i18nObserver;
}

export function getActiveLang(): 'es' | 'en' {
  if (typeof window !== 'undefined') {
    return ((localStorage.getItem('lang') || document.documentElement.lang || 'es') as 'es' | 'en');
  }
  return 'es';
}

export function t(key: string, lang?: 'es' | 'en'): string {
  const current = lang || getActiveLang();
  if (current === 'en') {
    return DICT[key] || key;
  }
  return REV[key] || key;
}

